import {test,expect} from '@playwright/test'
import {readFile} from 'node:fs/promises'
test('verified route uses real backend data, map, itinerary and export',async({page})=>{
 const errors:string[]=[];page.on('pageerror',error=>errors.push(error.message))
 await page.goto('/')
 await expect(page.getByRole('heading',{name:'Plan the route. Know the cost.'})).toBeVisible()
 await expect(page.getByText('API connected')).toBeVisible()
 const responsePromise=page.waitForResponse(r=>r.url().includes('/api/routes/optimize/')&&r.request().method()==='POST',{timeout:90000})
 await page.getByRole('button',{name:'Load verified route'}).click()
 const response=await responsePromise;expect(response.status()).toBe(200);const route=await response.json()
 expect(Number(route.distance_miles)).toBeGreaterThan(500);expect(route.fuel_stops.length).toBeGreaterThan(0)
 await expect(page.locator('.cost-card')).toContainText(Number(route.total_cost).toLocaleString('en-US',{style:'currency',currency:'USD'}))
 await expect(page.locator('.pin-body.fuel')).toHaveCount(route.fuel_stops.length)
 await expect(page.locator('.leaflet-overlay-pane path')).toHaveCount(2)
 await page.getByRole('button',{name:'Locate on map'}).first().click()
 await expect(page.locator('.station-popup strong')).toContainText(route.fuel_stops[0].name)
 const downloadPromise=page.waitForEvent('download');await page.getByRole('button',{name:'Export plan'}).click();const download=await downloadPromise
 const path=await download.path();const exported=JSON.parse(await readFile(path!,'utf8'));expect(exported.geometry.coordinates).toEqual(route.geometry.coordinates)
 await page.screenshot({path:'../data/processed/frontend-desktop.png',fullPage:true})
 expect(errors).toEqual([])
 await page.getByRole('button',{name:'Clear',exact:true}).click()
 await expect(page.locator('.leaflet-overlay-pane path')).toHaveCount(0)
 console.log(JSON.stringify({live_route_miles:route.distance_miles,total_cost:route.total_cost,stops:route.fuel_stops.length,directions_usage:route.provider_usage,tile_images:await page.locator('.leaflet-tile-loaded').count()}))
})
test('mobile route remains usable without horizontal overflow',async({page})=>{
 await page.setViewportSize({width:390,height:844});await page.goto('/')
 await page.getByRole('button',{name:'Load verified route'}).click()
 await expect(page.getByRole('heading',{name:'The fuel itinerary'})).toBeVisible({timeout:90000})
 await page.getByRole('button',{name:'Locate on map'}).first().click()
 await expect(page.locator('.station-popup')).toBeVisible()
 expect(await page.evaluate(()=>document.documentElement.scrollWidth-window.innerWidth)).toBeLessThanOrEqual(1)
 await page.screenshot({path:'../data/processed/frontend-mobile.png',fullPage:true})
})
test('actual insufficient coverage shows recovery without a fabricated plan',async({page})=>{
 await page.goto('/')
 await page.getByLabel('STARTING POINT').fill('29.7604, -95.3698')
 await page.getByLabel('DESTINATION',{exact:true}).fill('41.8781, -87.6298')
 await page.getByRole('button',{name:'Optimize route',exact:true}).click()
 await expect(page.getByRole('alert').filter({hasText:'Verified station coverage is insufficient'})).toBeVisible({timeout:90000})
 await expect(page.getByRole('button',{name:'Try the verified Midwest route'})).toBeVisible()
 await expect(page.locator('.leaflet-overlay-pane path')).toHaveCount(0)
 await page.getByRole('button',{name:'Try the verified Midwest route'}).click()
 await expect(page.getByRole('heading',{name:'The fuel itinerary'})).toBeVisible({timeout:90000})
})
